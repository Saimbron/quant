import { homedir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
const { Browser, sleep } = await import(pathToFileURL(join(homedir(), '.agents/skills/design-taste-frontend/scripts/lib/cdp.mjs')).href);
const b = await Browser.launch();
const p = await b.newPage({ width: 1440, height: 900 });
const bad = [];
await p.send('Network.enable');
b.on(p.sessionId, 'Network.responseReceived', (e) => { if (e.response.status >= 400) bad.push(e.response.status + ' ' + e.response.url); });
await p.goto('http://localhost:4323/quant/', { settleMs: 4000 });
const a = await p.eval(`({ coins: document.querySelector('.hero').classList.contains('has-coins'), result: document.querySelector('[data-result-text]').textContent })`);
await p.eval(`document.querySelector('.tab[href="/quant/cuota-autonomos/"]').click()`); await sleep(3000);
const c = await p.eval(`({ path: location.pathname, result: document.querySelector('[data-result-text]').textContent })`);
await p.eval(`scrollTo(0, 4000)`); await sleep(1500);
await p.eval(`document.querySelector('.bar-actions a[hreflang]').click()`); await sleep(3000);
const d = await p.eval(`({ path: location.pathname, lang: document.documentElement.lang })`);
await p.goto('http://localhost:4323/quant/no-existe/', { settleMs: 1000 });
const e = await p.eval(`({ title: document.title, home: document.querySelector('a.button')?.getAttribute('href') })`);
console.log(JSON.stringify({ a, c, d, e, bad: bad.filter((u) => !u.includes('no-existe')), errors: p.consoleErrors }, null, 1));
await b.close();
